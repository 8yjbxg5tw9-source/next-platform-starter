"""The bridge between the GUI widgets and the render backend.

Everything the Decoy-style UI can express lives in :class:`UIState`, and this
module is **pure Python** — no Tk, no subprocess.  That means the whole
"button -> FFmpeg flag" wiring is unit-testable headlessly, and the window
itself stays a thin renderer.

Mapping summary
---------------

========================  ======================================================
Widget                    Effect on the render
========================  ======================================================
Tier selector             picks a :class:`~reelforge.presets.Preset`
Motion blur switch        OFF -> no blur; ON -> ``tmix`` + 2x oversample
Motion blur slider        1-25 -> 2 frames, 26-50 -> 3, 51-75 -> 4, 76-100 -> 5
Output FPS selector       60 / 120 / source -> ``JobOptions.fps_override``
Sharpening switch         ON -> ``cas``, OFF -> sharpen disabled
Resolution selector       source / 1080x1920 / 720x1280 / 1080x1080 (cover crop)
Codec selector            H.264 / NVENC(GPU) / HEVC, with auto-fallback + note
========================  ======================================================
"""

